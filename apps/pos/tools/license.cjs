#!/usr/bin/env node
'use strict';
// Vendor tool for issuing device licenses. Keep the private key OFF the repo
// and off customer machines — whoever has it can activate any computer.
//
//   node tools/license.cjs keygen                     # once: create the key pair
//   node tools/license.cjs issue --machine 7F3A-91C2-04BE-D5E8-2A6F --customer "مكتبة النور" [--days 365]
//   node tools/license.cjs machine                    # print this computer's Machine ID
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { signLicense, machineId, normalizeId } = require('../electron/license.cjs');

const PUBLIC_KEY_FILE = path.join(__dirname, '..', 'electron', 'license-public.cjs');
const DEFAULT_PRIVATE = path.join(os.homedir(), '.innoforge', 'pos-license-private.pem');

function args() {
  const out = { _: [] };
  const argv = process.argv.slice(2);
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith('--')) out[argv[i].slice(2)] = argv[i + 1]?.startsWith('--') || argv[i + 1] === undefined ? true : argv[++i];
    else out._.push(argv[i]);
  }
  return out;
}

const a = args();
const privateFile = path.resolve(a.key || process.env.INNOFORGE_LICENSE_KEY || DEFAULT_PRIVATE);

switch (a._[0]) {
  case 'keygen': {
    if (fs.existsSync(privateFile) && !a.force) {
      console.error(`Private key already exists: ${privateFile}\nUse --force to replace it (all licenses issued with the old key stop working).`);
      process.exit(1);
    }
    const { privateKey, publicKey } = crypto.generateKeyPairSync('ed25519');
    fs.mkdirSync(path.dirname(privateFile), { recursive: true });
    fs.writeFileSync(privateFile, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
    const pem = publicKey.export({ type: 'spki', format: 'pem' }).trim();
    fs.writeFileSync(PUBLIC_KEY_FILE, `'use strict';
// Public half of the vendor license key (generated by tools/license.cjs keygen).
// Safe to ship: it can only verify licenses, not create them.
module.exports = \`${pem}
\`;
`);
    console.log(`Private key (keep secret, back it up): ${privateFile}`);
    console.log(`Public key written to: ${PUBLIC_KEY_FILE} — rebuild the installer so it ships this key.`);
    break;
  }
  case 'issue': {
    if (!a.machine || a.machine === true) {
      console.error('Missing --machine <Machine ID shown on the customer activation screen>');
      process.exit(1);
    }
    if (normalizeId(a.machine).length !== 20) {
      console.error('Machine ID looks wrong; expected 20 hex characters like 7F3A-91C2-04BE-D5E8-2A6F');
      process.exit(1);
    }
    if (!fs.existsSync(privateFile)) {
      console.error(`Private key not found: ${privateFile}\nRun "node tools/license.cjs keygen" first, or pass --key <file>.`);
      process.exit(1);
    }
    const days = a.days && a.days !== true ? Number(a.days) : null;
    const payload = {
      product: 'innoforge-pos',
      machine: normalizeId(a.machine).match(/.{4}/g).join('-'),
      customer: a.customer && a.customer !== true ? String(a.customer) : '',
      issued: new Date().toISOString(),
      expires: days ? new Date(Date.now() + days * 86400000).toISOString() : null,
    };
    console.log(signLicense(payload, fs.readFileSync(privateFile, 'utf8')));
    break;
  }
  case 'machine':
    console.log(machineId());
    break;
  default:
    console.log('Usage: node tools/license.cjs <keygen|issue|machine> [--machine ID] [--customer NAME] [--days N] [--key private.pem]');
}
